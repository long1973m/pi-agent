/**
 * 将 transcript 消息数组渲染为 HTML 消息流
 */
export function renderMessages(messages: TranscriptMessage[]): string {
  return messages
    .filter((m) => {
      if (m.role === "toolResult") return false;
      if (m.role === "branchSummary") return false;
      if (m.role === "compactionSummary") return false;
      if (m.role === "unknown") return false;
      if (m.role === "bashExecution") return false;
      return true;
    })
    .map((msg, index) => {
      const anchor = `msg-${index}`;
      const time = formatTime(msg.timestamp);

      switch (msg.role) {
        case "user":
          return renderBubble({
            anchor,
            cssClass: "bubble-user",
            label: "You",
            time,
            content: maskPII(msg.content).masked,
          });

        case "assistant":
          return renderAssistantBubble(msg, anchor, time, index);

        case "custom":
          return renderBubble({
            anchor,
            cssClass: "bubble-system",
            label: "System",
            time,
            content: msg.content,
          });

        default:
          return "";
      }
    })
    .join("\n");
}

/**
 * 渲染助手消息（含工具调用卡片）
 */
function renderAssistantBubble(
  msg: TranscriptMessage,
  anchor: string,
  time: string,
  index: number
): string {
  const parts: string[] = [];

  if (msg.content.trim()) {
    parts.push(renderBubble({
      anchor,
      cssClass: "bubble-assistant",
      label: "Assistant",
      time,
      content: msg.content,
    }));
  }

  if (msg.toolCalls && msg.toolCalls.length > 0) {
    for (const tc of msg.toolCalls) {
      parts.push(renderToolCallCard(tc, index));
    }
  }

  return parts.join("\n");
}

/**
 * 渲染工具调用摘要卡片
 */
function renderToolCallCard(tc: ToolCallInfo, msgIndex: number): string {
  const errorClass = tc.isError ? "tool-card-error" : "";
  const statusBadge = tc.isError
    ? '<span class="badge badge-error">ERROR</span>'
    : '<span class="badge badge-success">OK</span>';

  // 数据来源标签（仅 query_data / visualize）
  const dataSource = (tc.name === "query_data" || tc.name === "visualize")
    ? extractFirstTableName(tc.argsSummary)
    : null;
  const dataSourceHtml = dataSource
    ? `<span class="tool-data-source" title="数据来源">${escapeHtml(dataSource)}</span>`
    : "";

  // query_data 使用 SQL 高亮卡片
  const argsDisplay = tc.name === "query_data"
    ? renderSqlCard(tc.argsSummary)
    : `<pre class="args-raw">${escapeHtml(tc.argsSummary)}</pre>`;

  return `
<div class="tool-card ${errorClass}">
  <div class="tool-card-header">
    <span class="tool-name">${escapeHtml(tc.name)}</span>
    ${dataSourceHtml}
    ${statusBadge}
  </div>
  ${argsDisplay ? `<div class="tool-args">${argsDisplay}</div>` : ""}
  ${tc.resultSummary ? `<div class="tool-result">${escapeHtml(tc.resultSummary)}</div>` : ""}
</div>`;
}

/**
 * 从参数摘要中提取第一个表名（用于数据来源标签）
 */
function extractFirstTableName(argsSummary: string): string | null {
  try {
    const args = JSON.parse(argsSummary);
    const sql = args.sql;
    if (typeof sql !== "string") return null;
    const cleaned = sql
      .replace(/'[^']*'/g, "''")
      .replace(/--[^\n]*/g, "")
      .replace(/\/\*[\s\S]*?\*\//g, "");
    const m = cleaned.match(/\bFROM\s+([a-zA-Z_][a-zA-Z0-9_]*)/i);
    return m ? m[1] : null;
  } catch {
    return null;
  }
}

/**
 * 渲染 SQL 卡片 — 高亮 + 默认折叠前 3 行
 *
 * 使用 <details> 无需 JS，纯 HTML/CSS 实现展开/折叠。
 */
function renderSqlCard(argsSummary: string): string {
  let sql = "";
  try {
    const args = JSON.parse(argsSummary);
    sql = args.sql ?? "";
  } catch {
    // JSON 解析失败，尝试从摘要中提取
    const match = argsSummary.match(/"sql"\s*:\s*"([^"]*)"/);
    sql = match ? match[1] : argsSummary;
  }

  if (!sql) {
    return `<pre class="args-raw">${escapeHtml(argsSummary)}</pre>`;
  }

  const highlighted = highlightSql(sql);
  const first3 = getFirstLines(sql, 3);
  const highlightedFirst3 = highlightSql(first3);
  const needExpand = exceedsLines(sql, 3);

  const copyBtn = `<button class="sql-copy-btn" data-sql="${escapeHtml(sql)}" title="复制 SQL">复制</button>`;

  if (!needExpand) {
    return `<div class="sql-card">
  <div class="sql-card-header">
    <span class="sql-card-label">SQL</span>
    ${copyBtn}
  </div>
  <pre class="sql-card-body"><code>${highlighted}</code></pre>
</div>`;
  }

  // 超过 3 行：默认折叠，用 <details>
  return `<div class="sql-card">
  <div class="sql-card-header">
    <span class="sql-card-label">SQL</span>
    ${copyBtn}
  </div>
  <details class="sql-details">
    <summary class="sql-summary">
      <pre class="sql-preview"><code>${highlightedFirst3}</code></pre>
      <span class="sql-expand-hint">▼ 展开完整语句</span>
    </summary>
    <pre class="sql-card-body sql-full"><code>${highlighted}</code></pre>
  </details>
</div>`;
}

/**
 * 渲染单条消息气泡
 */
function renderBubble(params: {
  anchor: string;
  cssClass: string;
  label: string;
  time: string;
  content: string;
}): string {
  const { anchor, cssClass, label, time, content } = params;
  const htmlContent = formatContent(content);

  return `
<div class="bubble ${cssClass}" id="${anchor}">
  <div class="bubble-header">
    <span class="bubble-label">${label}</span>
    <span class="bubble-time">${time}</span>
  </div>
  <div class="bubble-body">${htmlContent}</div>
</div>`;
}

/**
 * 格式化消息内容（简单的 Markdown 渲染）
 */
function formatContent(text: string): string {
  if (!text) return "";

  let html = escapeHtml(text);

  // 代码块
  html = html.replace(/```(\w*)\n([\s\S]*?)```/g, (_m, _lang, code) => {
    return `<pre class="code-block"><code>${code.trim()}</code></pre>`;
  });

  // 行内代码
  html = html.replace(/`([^`]+)`/g, "<code class=\"inline-code\">$1</code>");

  // 粗体
  html = html.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");

  // 换行
  html = html.replace(/\n/g, "<br>");

  return html;
}

/**
 * 渲染图表区块
 */
export function renderChartsSection(inlineResults: Array<{
  inlined: boolean;
  originalPath: string;
  dataUri?: string;
  skipReason?: string;
}>): string {
  if (inlineResults.length === 0) return "";

  const items = inlineResults.map((r, i) => {
    if (r.inlined && r.dataUri) {
      return `<div class="chart-item">
  <img src="${r.dataUri}" alt="Chart ${i + 1}" class="chart-img" loading="lazy" />
  <p class="chart-path">${escapeHtml(r.originalPath)}</p>
</div>`;
    }
    return `<div class="chart-item chart-skipped">
  <p class="chart-skip-reason">${escapeHtml(r.skipReason ?? "Unknown")}</p>
  <p class="chart-path">${escapeHtml(r.originalPath)}</p>
</div>`;
  });

  return items.join("\n");
}

/**
 * 生成锚点导航目录
 */
export function renderToc(messages: TranscriptMessage[]): string {
  const items: string[] = [];
  let msgIndex = 0;

  for (const msg of messages) {
    if (msg.role === "toolResult" || msg.role === "branchSummary" ||
        msg.role === "compactionSummary" || msg.role === "unknown" ||
        msg.role === "bashExecution") continue;

    const anchor = `msg-${msgIndex}`;
    const time = formatTime(msg.timestamp);
    const preview = maskPII(msg.content.slice(0, 60).replace(/\n/g, " ")).masked;

    let label = "";
    switch (msg.role) {
      case "user":
        label = "You";
        break;
      case "assistant":
        label = "Assistant";
        break;
      case "custom":
        label = "System";
        break;
    }

    items.push(`<a href="#${anchor}" class="toc-item">
  <span class="toc-label">${label}</span>
  <span class="toc-preview">${escapeHtml(preview)}</span>
  <span class="toc-time">${time}</span>
</a>`);

    msgIndex++;
  }

  if (items.length === 0) return "";

  return `<h2 class="toc-title">Navigation</h2>\n${items.join("\n")}`;
}

