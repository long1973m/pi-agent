/**
 * Visualization Skill — SQL 查询模板
 *
 * 本文件提供各图表类型的 SQL 查询模板，供 Agent 参考使用。
 * 模板中的占位符需要替换为实际的表名和字段名。
 *
 * 占位符约定：
 *   {table}     — 目标表名
 *   {dim}       — 维度字段（分类/时间）
 *   {measure}   — 度量字段（数值）
 *   {measure_x} — X 轴数值字段
 *   {measure_y} — Y 轴数值字段
 *   {time_dim}  — 时间维度字段
 */

-- ============================================================================
-- bar: 分类比较
-- 用途：对比不同类别的数值大小
-- 要求：{dim} 为分类列，{measure} 为数值列
-- ============================================================================

-- 基础版本：按分类统计频次
SELECT {dim}, COUNT(*) AS cnt
FROM {table}
GROUP BY {dim}
ORDER BY {dim};

-- 聚合版本：按分类求平均/求和
SELECT {dim}, AVG({measure}) AS avg_measure
FROM {table}
GROUP BY {dim}
ORDER BY avg_measure DESC;

-- ============================================================================
-- line: 时间趋势
-- 用途：展示数据随时间变化的趋势
-- 要求：{time_dim} 为时间/有序字段，{measure} 为数值字段
-- ============================================================================

-- 基础版本：按时间求和
SELECT {time_dim}, SUM({measure}) AS total
FROM {table}
GROUP BY {time_dim}
ORDER BY {time_dim};

-- 移动平均（平滑趋势）：7 日移动平均
SELECT
  {time_dim},
  AVG({measure}) OVER (ORDER BY {time_dim} ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS moving_avg
FROM {table}
ORDER BY {time_dim};

-- ============================================================================
-- scatter: 两个数值变量的关系
-- 用途：分析两个数值变量之间的相关性
-- 要求：{measure_x} 和 {measure_y} 都是数值列
-- ============================================================================

-- 基础版本：散点数据 + 可选分组
SELECT {measure_x}, {measure_y}, {dim}
FROM {table};

-- ============================================================================
-- histogram: 单变量分布
-- 用途：了解单个数值变量的分布情况
-- 要求：{measure} 为数值列
-- ============================================================================

-- 基础版本：直接取数值列
SELECT {measure}
FROM {table};

-- ============================================================================
-- pie: 占比/构成
-- 用途：展示各部分占总体的比例
-- 要求：{dim} 为分类列
-- ============================================================================

-- 基础版本：按分类统计频次
SELECT {dim}, COUNT(*) AS cnt
FROM {table}
GROUP BY {dim};

-- ============================================================================
-- box: 多组统计分布对比
-- 用途：对比多组数据的统计分布特征
-- 要求：多个数值列，或一个分类列 + 一个数值列
-- ============================================================================

-- 多列版本：选择所有需要对比的数值列
-- 注意：以下占位符仅为示例，Agent 应根据实际数据集的数值列动态调整列数
SELECT {measure_1}, {measure_2}, {measure_3}, ...
FROM {table};

-- ============================================================================
-- heatmap: 多变量相关性矩阵
-- 用途：展示多个数值变量之间的相关性
-- 要求：多个数值列（建议 >= 3 个，否则用 scatter 更合适）
-- ============================================================================

-- 基础版本：选择所有需要计算相关性的数值列
-- 注意：以下占位符仅为示例，Agent 应根据实际数据集的数值列动态调整列数
SELECT {measure_1}, {measure_2}, {measure_3}, {measure_4}, ...
FROM {table};

-- ============================================================================
-- 辅助查询：字段类型检查
-- 在构造可视化查询前，先确认字段类型是否匹配图表需求
-- ============================================================================

-- 查看表的所有列及其类型
DESCRIBE {table};

-- 快速统计数值列的基本信息
SELECT
  MIN({measure}) AS min_val,
  MAX({measure}) AS max_val,
  AVG({measure}) AS avg_val,
  COUNT(DISTINCT {dim}) AS dim_cardinality
FROM {table};
